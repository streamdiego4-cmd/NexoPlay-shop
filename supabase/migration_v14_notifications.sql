-- Customer: order delivered
create or replace function public.nx_notify_order_status() returns trigger language plpgsql security definer set search_path=public as $$
begin
  if coalesce(old.delivery_status,'') is distinct from coalesce(new.delivery_status,'') and lower(coalesce(new.delivery_status,''))='delivered' and new.user_id is not null then
    perform public.nx_insert_notification(new.user_id,'user','delivery','📦 Pedido listo','Tu pedido '||coalesce(new.order_code,'')||' ya fue entregado. Revisa tus compras.',jsonb_build_object('order_id',new.id,'order_code',new.order_code));
  end if;
  return new;
end $$;
drop trigger if exists nx_order_status on public.nexoplay_orders;
create trigger nx_order_status after update on public.nexoplay_orders for each row execute function public.nx_notify_order_status();
